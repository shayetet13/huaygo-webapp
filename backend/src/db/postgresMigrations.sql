-- ── ตารางที่ PK ต้องเปลี่ยนเป็น composite (shop_id, ...) — Postgres ทำตรงๆ ได้ ไม่ต้อง rebuild ──
ALTER TABLE daily_stats ADD COLUMN IF NOT EXISTS shop_id INTEGER REFERENCES shops(id);
UPDATE daily_stats SET shop_id = 1 WHERE shop_id IS NULL;
ALTER TABLE daily_stats ALTER COLUMN shop_id SET NOT NULL;
DO $$
DECLARE cname text;
BEGIN
  SELECT conname INTO cname FROM pg_constraint WHERE conrelid = 'daily_stats'::regclass AND contype = 'p';
  IF cname IS NOT NULL AND cname != 'daily_stats_shop_pkey' THEN
    EXECUTE format('ALTER TABLE daily_stats DROP CONSTRAINT %I', cname);
    ALTER TABLE daily_stats ADD CONSTRAINT daily_stats_shop_pkey PRIMARY KEY (shop_id, date);
  END IF;
END $$;

