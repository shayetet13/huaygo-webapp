-- group_pay_rates: UNIQUE(group_name, bet_type) -> UNIQUE(shop_id, group_name, bet_type)
ALTER TABLE group_pay_rates ADD COLUMN IF NOT EXISTS shop_id INTEGER REFERENCES shops(id);
UPDATE group_pay_rates SET shop_id = 1 WHERE shop_id IS NULL;
ALTER TABLE group_pay_rates ALTER COLUMN shop_id SET NOT NULL;
DO $$
DECLARE cname text;
BEGIN
  SELECT conname INTO cname FROM pg_constraint
    WHERE conrelid = 'group_pay_rates'::regclass AND contype = 'u'
    AND conname != 'group_pay_rates_shop_unique';
  IF cname IS NOT NULL THEN
    EXECUTE format('ALTER TABLE group_pay_rates DROP CONSTRAINT %I', cname);
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conrelid = 'group_pay_rates'::regclass AND conname = 'group_pay_rates_shop_unique'
  ) THEN
    ALTER TABLE group_pay_rates ADD CONSTRAINT group_pay_rates_shop_unique UNIQUE(shop_id, group_name, bet_type);
  END IF;
END $$;

-- Phase 5: LIFF ลูกค้าแทงเอง — bets.user_id ผ่อนเป็น nullable + เพิ่ม customer_id
-- (โพยที่ staff คีย์มี user_id, โพยที่ลูกค้าแทงเองผ่าน LIFF มี customer_id — ต้องมีเป๊ะ 1 ใน 2)
ALTER TABLE bets ALTER COLUMN user_id DROP NOT NULL;
ALTER TABLE bets ADD COLUMN IF NOT EXISTS customer_id INTEGER REFERENCES customers(id);
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conrelid = 'bets'::regclass AND conname = 'bets_user_or_customer_chk'
  ) THEN
    ALTER TABLE bets ADD CONSTRAINT bets_user_or_customer_chk
      CHECK ((user_id IS NOT NULL AND customer_id IS NULL) OR (user_id IS NULL AND customer_id IS NOT NULL));
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS idx_bets_customer_id ON bets(customer_id, status, created_at DESC);

-- Phase 6: subscription lifecycle — plan + expires_at drive auto-suspend (subscription.service.ts)
-- TEXT + CHECK (not ENUM) to mirror the SQLite side exactly — same values, no ALTER TYPE migrations later.
ALTER TABLE shops ADD COLUMN IF NOT EXISTS plan TEXT;
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conrelid = 'shops'::regclass AND conname = 'shops_plan_chk'
  ) THEN
    ALTER TABLE shops ADD CONSTRAINT shops_plan_chk CHECK (plan IN ('free','monthly','annual') OR plan IS NULL);
  END IF;
END $$;

