CREATE TABLE IF NOT EXISTS shops (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug       TEXT UNIQUE NOT NULL,
  name       TEXT NOT NULL,
  mode       TEXT NOT NULL DEFAULT 'offline' CHECK (mode IN ('offline','online')),
  status     TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','suspended')),
  created_at TEXT NOT NULL DEFAULT now_local(),
  updated_at TEXT NOT NULL DEFAULT now_local()
);

ALTER TABLE shops ADD COLUMN IF NOT EXISTS expires_at TEXT;

CREATE TABLE IF NOT EXISTS shop_line_channels (
  shop_id            INTEGER PRIMARY KEY REFERENCES shops(id) ON DELETE CASCADE,
  channel_id         TEXT,
  channel_secret_enc TEXT,
  access_token_enc   TEXT,
  updated_at         TEXT NOT NULL DEFAULT now_local()
);

CREATE TABLE IF NOT EXISTS customers (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shop_id      INTEGER NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
  line_user_id TEXT,
  display_name TEXT,
  phone        TEXT,
  active       INTEGER NOT NULL DEFAULT 1,
  created_at   TEXT NOT NULL DEFAULT now_local(),
  UNIQUE(shop_id, line_user_id)
);
CREATE INDEX IF NOT EXISTS idx_customers_shop ON customers(shop_id);

