/** ค้นหาแบบ substring ทั้งสองทาง — คำค้นสั้นกว่า keyword (เช่นพิมพ์ "งู" เจอ "งูเขียว") หรือ
 *  ยาวกว่า (พิมพ์ "เห็นงูใหญ่" เจอ keyword "งู") ก็จับคู่ได้ทั้งคู่ ไม่ต้องพิมพ์ตรงเป๊ะ */
export function searchDream(query: string): DreamEntry[] {
  const q = query.trim()
  if (!q) return []
  return DREAM_DICTIONARY.filter((entry) =>
    entry.keywords.some((k) => k.includes(q) || q.includes(k)),
  )
}
